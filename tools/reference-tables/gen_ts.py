"""Generate Recipe Core's embedded copy of the sucrose reference table.

    python3 gen_ts.py ../../fixtures/reference-tables/nbs-c440-sucrose-20c.json ../../packages/recipe-core/src/formulas/data/sucrose-20c.ts

Recipe Core can't read files at run time (no Node or DOM APIs), so the
table is embedded. A test checks the module against the fixture.
"""
import json
import sys

doc = json.load(open(sys.argv[1], encoding="utf-8"))
rows = doc["rows"]
assert [r["plato"] for r in rows][::10] == [str(i) for i in range(41)]
sg = ", ".join(f'"{r["sg_20_20"]}"' for r in rows)
dens = ", ".join(f'"{r["density_20"]}"' for r in rows)
out = f"""// GENERATED by tools/reference-tables/gen_ts.py from
// fixtures/reference-tables/nbs-c440-sucrose-20c.json. Do not edit.
//
// {doc["source"]["citation"]}
// Underlying data: {doc["source"]["underlying_data"]}
// {doc["source"]["rights"]}.
// Index i is {{°P = i / 10}}, 0.0 to 40.0.

/** Apparent specific gravity at 20 °C/20 °C (Table 114, errata corrected). */
export const SG_20_20: readonly string[] = [{sg}];

/** True density at 20 °C in g/mL (Table 113, Plato 1900). */
export const DENSITY_20: readonly string[] = [{dens}];
"""
open(sys.argv[2], "w", encoding="utf-8").write(out)
print("wrote", sys.argv[2])
